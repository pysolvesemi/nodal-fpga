"""Exact registry package/graph/source gate, separate from project unsafe lints.

The checked-in inventory is a reviewed input, never regenerated by a check.
All Cargo-declared dependency kinds/targets/aliases and feature maps are frozen,
including inactive dependencies. The resolved graph freezes activated features.
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
from pathlib import Path
import tomllib

REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
FIELDS = ("name", "version", "source", "id", "dependencies", "features", "links",
          "license", "rust_version", "edition", "publish")


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def source_tree(path: Path) -> str:
    records = []
    for file in sorted(path.rglob("*"), key=lambda p: p.relative_to(path).as_posix()):
        if file.is_symlink():
            raise ValueError("registry source symlink")
        if file.is_file() and file.relative_to(path).as_posix() != ".cargo-ok":
            records.append([file.relative_to(path).as_posix(), digest(file)])
    return hashlib.sha256(json.dumps(records, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def package_record(package: dict) -> dict:
    directory = Path(package["manifest_path"]).parent
    record = {key: copy.deepcopy(package[key]) for key in FIELDS}
    record["targets"] = copy.deepcopy(package["targets"])
    for target in record["targets"]:
        source = Path(target["src_path"])
        if not source.is_relative_to(directory) or source.resolve() != source:
            raise ValueError("noncanonical registry target")
        target["src_path"] = source.relative_to(directory).as_posix()
    return record


def load(root: Path) -> dict:
    from check_boundaries import reject, _unique_object, _plain_path
    path = root / "tools/dependencies/rust-registry.json"
    _plain_path(path, root, "NF-OWN-POLICY")
    data = json.loads(path.read_text(), object_pairs_hook=_unique_object)
    if set(data) != {"schema", "source", "packages", "nodes", "lock_packages"} or data["schema"] != 1 or data["source"] != REGISTRY:
        reject("NF-OWN-POLICY", "malformed registry inventory")
    ids = [p["metadata"]["id"] for p in data["packages"]]
    if len(ids) != len(set(ids)) or len(ids) != len(data["nodes"]):
        reject("NF-OWN-POLICY", "duplicate or missing registry identities")
    for package in data["packages"]:
        if set(package) != {"metadata", "checksum", "source_tree_sha256", "hooks"}:
            reject("NF-OWN-POLICY", "malformed registry package record")
        item = package["metadata"]
        if item["source"] != REGISTRY or item["id"] != f'{REGISTRY}#{item["name"]}@{item["version"]}':
            reject("NF-OWN-POLICY", "unexpected registry identity")
        for key in ["checksum", "source_tree_sha256"]:
            if not isinstance(package[key], str) or len(package[key]) != 64 or any(c not in "0123456789abcdef" for c in package[key]):
                reject("NF-OWN-POLICY", "invalid registry checksum")
    return data


def check_lock(root: Path, local: dict, internal: set, direct: list) -> dict:
    from check_boundaries import reject, _plain_path
    inventory = load(root)
    path = root / "Cargo.lock"
    _plain_path(path, root, "NF-OWN-LOCK")
    lock = tomllib.loads(path.read_text())
    expected = copy.deepcopy(inventory["lock_packages"])
    for name, package in local.items():
        dependencies = sorted({edge[1] for edge in internal if edge[0] == name}
                              | {edge["to"] for edge in direct if edge["from"] == name})
        item = {"name": name, "version": package["version"]}
        if dependencies:
            item["dependencies"] = dependencies
        expected.append(item)
    if lock.get("version") != 4 or sorted(lock.get("package", []), key=lambda p: (p["name"], p["version"])) != sorted(expected, key=lambda p: (p["name"], p["version"])):
        reject("NF-OWN-LOCK", "Cargo.lock differs from reviewed identities/checksums/edges")
    return inventory


def check_metadata(root: Path, data: dict, local: dict, direct: list, inventory: dict) -> dict:
    """Verify every registry package and remove only reviewed edges for the local DAG gate."""
    from check_boundaries import reject
    def require(condition, detail):
        if not condition:
            reject("NF-CORE-GRAPH", detail)
    expected = {p["metadata"]["id"]: p for p in inventory["packages"]}
    observed = {}
    for item in data["packages"]:
        if item["source"] is None:
            continue
        require(item["id"] in expected and item["id"] not in observed, "unreviewed registry identity")
        record = expected[item["id"]]
        require(package_record(item) == record["metadata"], "registry declaration/target/feature/hook drift")
        directory = Path(item["manifest_path"]).parent
        require(directory.resolve() == directory and directory.name == f'{item["name"]}-{item["version"]}', "registry source path drift")
        # Cargo's standard registry source/cache layout is explicit. Git/vendor
        # replacements or alternative registries require a new ownership review.
        require(directory.parent.parent.name == "src" and directory.parent.parent.parent.name == "registry", "noncanonical registry source cache")
        archive = directory.parent.parent.parent / "cache" / directory.parent.name / (directory.name + ".crate")
        require(archive.is_file() and not archive.is_symlink() and digest(archive) == record["checksum"], "registry archive checksum mismatch")
        require(source_tree(directory) == record["source_tree_sha256"], "registry extracted source checksum mismatch")
        observed[item["id"]] = item
    require(set(observed) == set(expected), "missing registry package")
    nodes = data["resolve"]["nodes"]
    registry_nodes = [node for node in nodes if node["id"] in expected]
    require(sorted(registry_nodes, key=lambda x: x["id"]) == inventory["nodes"], "registry resolved edges/features differ from reviewed graph")
    result = copy.deepcopy(data)
    result["packages"] = [item for item in result["packages"] if item["source"] is None]
    result["resolve"]["nodes"] = [node for node in result["resolve"]["nodes"] if node["id"] not in expected]
    ids = {item["name"]: item["id"] for item in result["packages"]}
    for name in local:
        package = next(item for item in result["packages"] if item["name"] == name)
        required = [edge for edge in direct if edge["from"] == name]
        declarations = [dep for dep in package["dependencies"] if dep["source"] is not None]
        desired = []
        for edge in required:
            dep = edge["declaration"]
            desired.append({"name": edge["to"], "source": REGISTRY, "req": dep["version"],
                            "kind": None if edge["kind"] == "normal" else edge["kind"],
                            "rename": None, "optional": False,
                            "uses_default_features": dep.get("default-features", True),
                            "features": dep.get("features", []), "target": edge["target"], "registry": None})
        require(sorted(declarations, key=lambda x: x["name"]) == sorted(desired, key=lambda x: x["name"]), "local registry dependency declaration drift")
        package["dependencies"] = [dep for dep in package["dependencies"] if dep["source"] is None]
        node = next(node for node in result["resolve"]["nodes"] if node["id"] == ids[name])
        external_ids = {p["metadata"]["id"] for p in inventory["packages"] if any(edge["to"] == p["metadata"]["name"] for edge in required)}
        external = [dep for dep in node["deps"] if dep["pkg"] in expected]
        expected_deps = [{"name": edge["alias"].replace("-", "_"),
                          "pkg": next(p["metadata"]["id"] for p in inventory["packages"] if p["metadata"]["name"] == edge["to"]),
                          "dep_kinds": [{"kind": None if edge["kind"] == "normal" else edge["kind"], "target": edge["target"]}]} for edge in required]
        require(sorted(external, key=lambda x: x["name"]) == sorted(expected_deps, key=lambda x: x["name"]), "local registry resolved edge drift")
        require([p for p in node["dependencies"] if p in expected] == sorted(external_ids), "local registry resolved IDs drift")
        node["dependencies"] = [p for p in node["dependencies"] if p not in expected]
        node["deps"] = [dep for dep in node["deps"] if dep["pkg"] not in expected]
    print(f"reviewed_registry_packages={len(expected)} complete_declared_and_resolved_graph=checked source_archives_and_trees=checked")
    return result
